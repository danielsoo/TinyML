# PlatformIO pre-build script: embeds the models of the device bundle (path in bundle.txt,
# relative to the repo root) as 16-byte-aligned C arrays plus a name table.
import json
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    PROJECT_DIR = env["PROJECT_DIR"]  # noqa: F821
except NameError:  # plain `python gen_model_data.py`
    PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))

REPO = os.path.dirname(PROJECT_DIR)
OUT_CC = os.path.join(PROJECT_DIR, "src", "model_data.cc")
OUT_H = os.path.join(PROJECT_DIR, "include", "model_data.h")


def generate():
    with open(os.path.join(PROJECT_DIR, "bundle.txt"), encoding="utf-8") as f:
        bundle = os.path.join(REPO, f.read().strip())
    with open(os.path.join(bundle, "bundle.json"), encoding="utf-8") as f:
        models = json.load(f)["models"]
    header = ["// Auto-generated by gen_model_data.py - do not edit.", "#pragma once", "",
              "struct ModelEntry { const char* name; const unsigned char* data; unsigned int len; };",
              f"constexpr int kNumModels = {len(models)};", "extern const ModelEntry kModels[];", ""]
    source = ["// Auto-generated by gen_model_data.py - do not edit.", '#include "model_data.h"', ""]
    for i, m in enumerate(models):
        with open(os.path.join(bundle, m["file"]), "rb") as f:
            data = f.read()
        source.append(f"// {m['name']}: {m['file']} ({len(data)} bytes)")
        source.append(f"alignas(16) static const unsigned char kModel{i}[] = {{")
        for j in range(0, len(data), 16):
            source.append("  " + ", ".join(f"0x{b:02x}" for b in data[j:j + 16]) + ",")
        source += ["};", ""]
    source.append("const ModelEntry kModels[] = {")
    for i, m in enumerate(models):
        source.append(f'  {{"{m["name"]}", kModel{i}, sizeof(kModel{i})}},')
    source.append("};")
    with open(OUT_H, "w", newline="\n") as f:
        f.write("\n".join(header) + "\n")
    with open(OUT_CC, "w", newline="\n") as f:
        f.write("\n".join(source) + "\n")
    print(f"[gen_model_data] {len(models)} models from {bundle}")


generate()
